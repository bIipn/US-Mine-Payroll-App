"""
Writes src/services/pdfMetrics.ts: the advance widths of the PDF standard fonts Helvetica and
Helvetica-Bold for every character of WinAnsiEncoding (codes 32 to 255), in thousandths of the
font size. They are Adobe's published metrics for the standard 14 fonts, which every PDF reader
has built in, so a PDF can use them without embedding a font. Read here from ReportLab.

    python3 scripts/make-pdf-metrics.py
"""
import os

from reportlab.pdfbase.pdfmetrics import getFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def widths(name):
    font = getFont(name)
    out = []
    for code in range(32, 256):
        try:
            ch = bytes([code]).decode('cp1252')
        except UnicodeDecodeError:
            out.append(0)
            continue
        out.append(round(font.stringWidth(ch, 1000)))
    return out


def main():
    lines = [
        '// Generated by scripts/make-pdf-metrics.py from Adobe\'s metrics for the PDF standard fonts. Do not edit by hand.',
        '// Advance widths in thousandths of the font size, for WinAnsiEncoding codes 32 to 255 (index 0 is code 32).',
        '',
    ]
    for key, name in (('regular', 'Helvetica'), ('bold', 'Helvetica-Bold')):
        w = widths(name)
        rows = [', '.join(str(x) for x in w[i:i + 16]) for i in range(0, len(w), 16)]
        lines.append(f'const {key.upper()} = [')
        lines += [f'  {row},' for row in rows]
        lines.append('];')
        lines.append('')
    lines.append('export const PDF_WIDTHS = { regular: REGULAR, bold: BOLD } as const;')
    path = os.path.join(ROOT, 'src', 'services', 'pdfMetrics.ts')
    with open(path, 'w') as f:
        f.write('\n'.join(lines) + '\n')


if __name__ == '__main__':
    main()
